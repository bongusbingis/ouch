"""Generate Roblox artwork bindings from approved, hash-matched gate results."""
import json
from workflow_common import ROOT, digest, read_json


def main():
    plan = read_json(ROOT / "tools/redesign-assets.json")
    assets = read_json(ROOT / "manifests/assets.json")["assets"]
    textures = {entry["file"]: entry.get("roblox", {}) for entry in plan["assets"]}
    def asset_id(path):
        record = assets.get(path)
        if not record:
            return ""
        if record.get("moderation_state") != "MODERATION_STATE_APPROVED" or record.get("sha256") != digest((ROOT / path).read_bytes()):
            raise ValueError(f"Unapproved or stale artwork: {path}")
        texture = textures[path]
        if str(texture.get("decal_asset_id", "")) != str(record["asset_id"]) or not str(texture.get("image_asset_id", "")).isdigit():
            raise ValueError(f"Resolve the approved Decal.Texture in Studio before binding: {path}")
        return "rbxassetid://" + str(texture["image_asset_id"])
    lines = ["--!strict", "-- Generated by tools/sync_redesign_assets.py from approved asset-gate results.", "return {", "\tPage = " + json.dumps(asset_id("assets/ui/page-panel-9slice.png")) + ",", "\tWell = " + json.dumps(asset_id("assets/ui/well-9slice.png")) + ",", "\tIcons = {"]
    for key, entry in plan["icons"].items():
        x, y = entry["offset"]
        w, h = entry["size"]
        lines.append(f'\t\t{key} = {{ Image = {json.dumps(asset_id(entry["file"]))}, Offset = Vector2.new({x}, {y}), Size = Vector2.new({w}, {h}) }},')
    lines += ["\t},", "}"]
    path = ROOT / "src/config/Interface/RedesignArtwork.luau"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\r\n")
    workflow = read_json(ROOT / "tools/workflow.json")
    for key, entry in plan["icons"].items():
        workflow["canonical_icons"][key] = {**entry, "asset_id": asset_id(entry["file"])}
    (ROOT / "tools/workflow.json").write_text(json.dumps(workflow, indent=2) + "\n", encoding="utf-8")
    print("Updated artwork bindings from approved decals and verified image textures.")


if __name__ == "__main__":
    main()
